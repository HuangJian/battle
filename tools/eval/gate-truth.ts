#!/usr/bin/env bun
/**
 * gate-truth.ts — Generate the god-ai-regression-gate TRUTH_WIN_PCT table
 * from an eval-suite --json dump.
 *
 * After any shipped God-AI behavior change, the regression gate's truth
 * values must be re-measured (35×60 classic, DECISIONS §94):
 *
 *   1. bun tools/eval/eval-suite.ts --seeds 60 --json tmp/shipped.json
 *   2. bun tools/eval/gate-truth.ts tmp/shipped.json
 *   3. paste the emitted table into tests/gate-core.ts
 *      (<DIFF>_TRUTH_WINS, then TRUTH map), keeping any conservative
 *      exceptions (e.g. S28's gate-context noise floor — see the gate
 *      file's own notes).
 *
 * The table is emitted as paste-ready TS: one line per stage with the name
 * comment and the exact win rate eval-suite measured. Also prints the
 * aggregate mean + the resulting AGGREGATE_FLOOR (truth − 3.7pp at n=700,
 * the gate's current convention).
 *
 * Usage:
 *   bun tools/eval/gate-truth.ts <eval-suite-json> [--min-gain 1.0]
 */
import { readFileSync } from 'node:fs'
import { STAGES } from '../../src/config/stages'

const USAGE = `
gate-truth.ts — generate TRUTH_WIN_PCT from an eval-suite --json dump.

Usage:
  bun tools/eval/gate-truth.ts <eval-suite-json>

The input is produced by:
  bun tools/eval/eval-suite.ts --seeds 60 --json tmp/shipped.json

Emit the table into tests/gate-core.ts TRUTH arrays, then re-run:
  bun test tests/godai-score-gate.test.ts (score gate) / the gate part files
`

const path = process.argv[2]
if (!path) {
  console.error(USAGE)
  process.exit(1)
}

interface DumpStage {
  stageName: string
  winRate: number
  runs: number
}
interface Dump {
  stages: DumpStage[]
  suite: { meanWinRate: number }
}

const dump = JSON.parse(readFileSync(path, 'utf8')) as Dump
if (!dump.stages || dump.stages.length === 0) {
  console.error(`gate-truth: no per-stage data in ${path} (expected an eval-suite --json dump)`)
  process.exit(1)
}

// Match by index: eval-suite emits stages in stage order (0..34). Verify the
// names line up so a reordered dump can't silently misalign the table.
let mismatch = 0
console.log('// TRUTH_WIN_PCT — regenerated by bun tools/eval/gate-truth.ts:')
console.log(
  `//   eval-suite --seeds ${dump.stages[0]?.runs ?? 60} classic, mean ${(dump.suite.meanWinRate * 100).toFixed(2)}%`,
)
console.log('const TRUTH_WIN_PCT: number[] = [')
for (let idx = 0; idx < STAGES.length; idx++) {
  const s = dump.stages[idx]
  if (!s) {
    console.error(
      `gate-truth: dump has only ${dump.stages.length} stages, expected ${STAGES.length}`,
    )
    process.exit(1)
  }
  const pct = (s.winRate * 100).toFixed(1)
  const name = STAGES[idx].name
  if (s.stageName !== name) {
    mismatch++
    console.error(
      `gate-truth: stage ${idx} name mismatch — dump '${s.stageName}' vs config '${name}'`,
    )
  }
  const line = `  ${pct.padStart(5)}, // S${idx + 1}  ${name}`
  console.log(line)
}
console.log(']')
if (mismatch > 0) {
  console.error(`gate-truth: ${mismatch} stage-name mismatches — table is NOT safe to paste`)
  process.exit(1)
}

// Aggregate floor: truth mean − 3.7pp (3 binomial sd at n=700), per gate file
// convention Math.floor(0.872 * 700). The gate hardcodes 0.872 (from the
// 90.9% shipped mean); the 2-decimal mean below keeps a regenerated table
// self-consistent with what the gate will compute from it.
const meanPct = dump.suite.meanWinRate * 100
const floor = Math.floor(((meanPct - 3.7) / 100) * 700)
console.log(`\n// aggregate mean ${meanPct.toFixed(2)}% → AGGREGATE_FLOOR = ${floor} (of 700)`)
console.log(
  `//   gate convention: Math.floor((mean − 3.7pp)/100 × 700) = ${Math.floor(((meanPct - 3.7) / 100) * 700)}`,
)
