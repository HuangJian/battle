"""`tests/helpers/budget.py` — 存量基线类门禁的**自检地板**（唯一实现）。

背景（2026-11-15）：G4 / G9 这类「按文件冻结存量」的门禁都带一条扫描入口自检 ——
`assert sum(actual) >= 地板`，用来抓「AST 没数到东西」（walk 坏了、扫描面写错、包名改了）。
它和「存量多少」没有关系，但历史上写成绝对值，于是每次合法清理基线都要顺手回填一个与之无关
的数字：同一天里改了三次（423 → 397 → 398、51 → 44 → 40 → 35），三次都可能写错，而且
「这次该写多少」没有任何判据可依。

现在地板 = 基线的 `SANITY_RATIO`（9 成，向下取整）：
  * 清理让基线变小 ⇒ 地板自动跟着变小，不需要人工回填；
  * 扫描返回 0 / 少了一半 ⇒ 仍然红（它必须显著低于基线才可能过）；
  * 基线被清空 ⇒ 地板 0，但那条路由各门禁自己的「锚文件非零」断言兜住。

为什么不取 0.5：这条断言的成本是「一次误红」，收益是「扫描入口坏掉时立刻知道」。
9 成留出的 10% 只够容纳「一两个文件完全掉出扫描面」，再多就该红。
"""

from __future__ import annotations

#: 地板相对基线的比例（见模块 docstring 的口径说明）。
SANITY_RATIO = 0.9


def sanity_floor_of(total: int) -> int:
    """单个计数器的地板：该计数器基线的 9 成（向下取整）。

    给「基线不是 `{文件: 整数}` 一张表」的门禁用（G6 抑制符按类别分两表、文本断言两个口径）。
    """
    return int(total * SANITY_RATIO)


def sanity_floor(baseline: dict[str, int]) -> int:
    """扫描入口自检的地板：基线总和的 9 成（向下取整；空基线 ⇒ 0）。"""
    return sanity_floor_of(sum(baseline.values()))
